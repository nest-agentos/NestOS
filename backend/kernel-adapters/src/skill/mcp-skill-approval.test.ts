import {expect,it,vi} from 'vitest';
import {Kernel} from '@nestos/durable-kernel';
import {createVFS,MemoryBackend} from '@nestos/vfs-core';
import {sha256HexSync} from '@nestos/llm-context';
import {McpSkillApprovalProgram} from '../programs/approved-effect-program';
import {McpSkillSource} from './mcp-skill-source';
import {SkillDeviceDriver} from './skill-device-driver';
import {createSessionSkillControls} from './session-skill-controls';

it('binds the actual user approval to the session, origin, manifest and acting window',async()=>{
 const {manager}=await createVFS({rootBackend:new MemoryBackend()});const fs=await manager.openFileSystem('/approval');
 const kernel=new Kernel({catalog:{fs},pollMs:0});kernel.registerStorageResolver({kind:'test',async resolve(){return {fs,rootPath:'/session'};}});
 kernel.registerProgram(new McpSkillApprovalProgram());await kernel.initialize();
 const session=await kernel.createSession({id:'session',storage:{kind:'test',locator:null}});
 const uri='skill://example/SKILL.md',text='---\nname: example\ndescription: Example\n---\nBody\n';
 const entry={uri,frontmatter:{name:'example',description:'Example'},resources:[{uri,digest:'sha256:'+sha256HexSync(text),size:new TextEncoder().encode(text).length}]};
 const read=vi.fn(async()=>new TextEncoder().encode(text));
 const source=new McpSkillSource('origin',{listMcpSkills:async()=>[entry],getMcpSkill:async()=>entry,readMcpSkillBytes:read},'frozen-scope');const service=new SkillDeviceDriver({source});await service.setCwd('/workspace');
 const skillId=service.getScopedSkills()[0].id;const makeScope=()=>({skillService:service,readMcpSkillApproved:source.readApproved.bind(source)});
 let scope=makeScope();const controls=createSessionSkillControls(kernel,{get:async()=>scope} as never);
 try {
  const window=await controls.mcpApprovalWindow!('session');
  const id=await controls.requestMcpApproval!('session',skillId,'approve-one',window);const task=await session.attachTask(id);
  await vi.waitFor(async()=>expect((await task.status()).task.interactions['approve:mcp-skill']?.status).toBe('pending'));
  expect((await task.status()).task.input).toMatchObject({serverId:'origin',scopeId:'frozen-scope',uri});
  expect(await controls.verifyMcpApproval!('session',id,skillId,window)).toBe(false);
  await task.respond({interactionId:'approve:mcp-skill',value:true});expect((await task.wait({timeoutMs:5000})).status).toBe('succeeded');
  expect(await controls.verifyMcpApproval!('session',id,skillId,window)).toBe(true);
  await expect(controls.verifyMcpApproval!('session',id,skillId,'other-window')).rejects.toThrow('MCP_SKILL_WINDOW_CHANGED');
  expect(await controls.readMcpApproved!('session',skillId,id,window)).toBe(text);expect(read).toHaveBeenCalledTimes(1);
  const gate=(scope as unknown as import('../ports/capabilities').SessionCapabilityScope).validateMcpSkillWindow!;
  expect(await gate(service.getSkill(skillId)!)).toBe(true);
  const otherSource=new McpSkillSource('other-node',{listMcpSkills:async()=>[entry]},'frozen-scope');
  const otherService=new SkillDeviceDriver({source:otherSource});await otherService.setCwd('/workspace');
  const firstService=scope.skillService;scope.skillService=otherService;
  expect(await gate(firstService.getSkill(skillId)!)).toBe(false);
  await expect(controls.verifyMcpApproval!('session',id,skillId,window)).rejects.toThrow('MCP_SKILL_UNAVAILABLE');
  await expect(controls.readMcpApproved!('session',skillId,id,window)).rejects.toThrow('MCP_SKILL_UNAVAILABLE');
  scope.skillService=firstService;await otherService.dispose();expect(read).toHaveBeenCalledTimes(1);
  const otherScopeSource=new McpSkillSource('origin',{listMcpSkills:async()=>[entry]},'replacement-scope');
  const otherScopeService=new SkillDeviceDriver({source:otherScopeSource});await otherScopeService.setCwd('/workspace');
  scope.skillService=otherScopeService;
  await expect(controls.verifyMcpApproval!('session',id,skillId,window)).rejects.toThrow('MCP_SKILL_UNAVAILABLE');
  await expect(controls.readMcpApproved!('session',skillId,id,window)).rejects.toThrow('MCP_SKILL_UNAVAILABLE');
  scope.skillService=firstService;await otherScopeService.dispose();expect(read).toHaveBeenCalledTimes(1);
  let finish!:(value:Uint8Array)=>void,entered!:()=>void;const started=new Promise<void>(resolve=>{entered=resolve;});
  read.mockImplementationOnce(()=>{entered();return new Promise(resolve=>{finish=resolve;});});
  const pending=source.readApproved('session',skillId,id,window,controls);await started;
  const previousScope=scope;scope=makeScope();finish(new TextEncoder().encode(text));
  expect(await gate(firstService.getSkill(skillId)!)).toBe(false);
  await expect(pending).rejects.toThrow('MCP_SKILL_WINDOW_CHANGED');scope=previousScope;
  await expect(controls.readMcpApproved!('session',skillId,id,'other-window')).rejects.toThrow('MCP_SKILL_WINDOW_CHANGED');expect(read).toHaveBeenCalledTimes(2);
  const deniedId=await controls.requestMcpApproval!('session',skillId,'approve-two',window);const denied=await session.attachTask(deniedId);
  await vi.waitFor(async()=>expect((await denied.status()).task.interactions['approve:mcp-skill']?.status).toBe('pending'));
  await denied.respond({interactionId:'approve:mcp-skill',value:false});expect((await denied.wait({timeoutMs:5000})).status).toBe('failed');
  expect(await controls.verifyMcpApproval!('session',deniedId,skillId,window)).toBe(false);
  await expect(controls.readMcpApproved!('session',skillId,deniedId,window)).rejects.toThrow('MCP_SKILL_APPROVAL_DENIED');expect(read).toHaveBeenCalledTimes(2);
  entry.resources[0].digest='sha256:'+'f'.repeat(64);await service.refreshScopedSkills();
  expect(await controls.verifyMcpApproval!('session',id,skillId,window)).toBe(false);
  await expect(source.readApproved('session',skillId,id,window,controls)).rejects.toThrow('MCP_SKILL_APPROVAL_DENIED');expect(read).toHaveBeenCalledTimes(2);
  scope=makeScope();expect(await controls.mcpApprovalWindow!('session')).not.toBe(window);
  await expect(controls.verifyMcpApproval!('session',id,skillId,window)).rejects.toThrow('MCP_SKILL_WINDOW_CHANGED');
 } finally {await service.dispose();await kernel.dispose();await manager.dispose();}
},20_000);
